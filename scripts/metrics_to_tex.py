#!/usr/bin/env python3
r"""Emit results/metrics.json as LaTeX macros for the paper.

Each key becomes \expandafter\def\csname metric@<key>\endcsname{<value>} and \metric{<key>}
expands to it; an unknown key stops the build (\errmessage). Floats are rounded to 3
significant figures with at most 3 decimals (no exponent), integral values print without decimals, '_' is escaped.
"""
import json
import math
from decimal import ROUND_HALF_UP, Decimal
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = r"""% generated by scripts/metrics_to_tex.py from results/metrics.json -- do not edit
\newcommand{\metric}[1]{\ifcsname metric@#1\endcsname\csname metric@#1\endcsname\else\errmessage{missing metric #1}\fi}
"""


def sig3(v: float) -> str:
    if v == 0 or not math.isfinite(v):
        return "0" if v == 0 else str(v)
    digits = min(3 - int(math.floor(math.log10(abs(v)))) - 1, 3)  # 3 sig. figures, at most 3 decimals
    # half-up on the exact binary value, like JavaScript's toFixed()/Math.round() used by the
    # report and slide builders, so all three documents print identical digits
    q = Decimal(v).quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
    return f"{q:f}" if digits > 0 else str(int(q))


def fmt(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v == int(v) and abs(v) < 1e6:
            return str(int(v))
        return sig3(v)
    return str(v).replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


def to_tex(metrics: dict) -> str:
    lines = [HEADER]
    for k in sorted(metrics):
        lines.append(rf"\expandafter\def\csname metric@{k}\endcsname{{{fmt(metrics[k])}}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results" / "metrics.json"
    metrics = json.loads(path.read_text())
    if "pnr5.status" in metrics:
        # wording that depends on the 5 ns result (scripts/pnr5_text.py), not on fixed text
        sys.path.insert(0, str(ROOT / "scripts"))
        from pnr5_text import describe
        metrics.update(describe(metrics))
    sys.stdout.write(to_tex(metrics))


if __name__ == "__main__":
    main()
